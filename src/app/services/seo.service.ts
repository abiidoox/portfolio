import { Injectable, inject, DOCUMENT } from '@angular/core';
import { Title, Meta } from '@angular/platform-browser';
import { Router, ActivatedRoute, NavigationEnd, Data } from '@angular/router';
import { TranslateService } from '@ngx-translate/core';
import { filter, merge } from 'rxjs';
import { LanguageService, Language } from './language.service';

const SITE = 'https://abderrazzaq-portfolio.netlify.app';
const OG_LOCALE: Record<Language, string> = { en: 'en_US', fr: 'fr_FR', es: 'es_ES' };
/** '' and '/about' render the same About page, so they share one canonical. */
const ALIASES: Record<string, string> = { '': '/', '/about': '/' };

/**
 * 1200x630 social cards, one per route and per project, generated by
 * tools/build-og.cjs and committed to src/assets/og/.
 */
const OG_IMAGE_BY_ROUTE: Record<string, string> = {
  '/': 'assets/og/home.png',
  '/projects': 'assets/og/projects.png',
  '/skills': 'assets/og/skills.png',
  '/resume': 'assets/og/resume.png',
  '/contact': 'assets/og/contact.png',
  '/404': 'assets/og/404.png'
};

function ogImageFor(path: string): string {
  const prefix = '/projects/';
  if (path.startsWith(prefix)) {
    const slug = path.slice(prefix.length).replace(/\/+$/, '');
    if (slug) return `assets/og/project-${slug}.png`;
  }
  return OG_IMAGE_BY_ROUTE[path] ?? 'assets/og/home.png';
}

@Injectable({ providedIn: 'root' })
export class SeoService {
  private router = inject(Router);
  private route = inject(ActivatedRoute);
  private title = inject(Title);
  private meta = inject(Meta);
  private translate = inject(TranslateService);
  private languageService = inject(LanguageService);
  private doc = inject(DOCUMENT);

  constructor() {
    // Route changes and language changes both have to refresh the head tags.
    // onLangChange is used rather than languageService.currentLanguage$ because
    // that stream fires before translate.use() resolves, which would read the
    // previous language's dictionary and leave the title a language behind.
    merge(
      this.router.events.pipe(filter(e => e instanceof NavigationEnd)),
      this.translate.onLangChange
    ).subscribe(() => this.apply());
  }

  /** Case-study pages publish their runtime copy here; see setOverride(). */
  private override: Data | null = null;

  /**
   * Case-study pages resolve translated copy from data at runtime (route data
   * is static), so they publish ready strings here. Pass null when leaving.
   */
  setOverride(data: Data | null): void {
    this.override = data;
    this.apply();
  }

  /** Route data for the deepest activated route, which is where lazy routes put it. */
  private deepestData(): Data {
    let route = this.route.snapshot;
    while (route.firstChild) route = route.firstChild;
    return route.data ?? {};
  }

  private text(key: string | undefined | null): string {
    if (!key) return '';
    // instant() echoes the key back when a translation is missing, which would
    // silently ship "ABOUT.TITLE" into a <title> or meta tag.
    const value = this.translate.instant(key);
    return value === key ? '' : value;
  }

  private metaContent(data: Data, field: 'name' | 'property', value: string, literal = false): string {
    const entries = (data['meta'] ?? []) as { name?: string; property?: string; content: string }[];
    const match = entries.find(e => e[field] === value);
    if (!match) return '';
    return literal ? match.content : this.text(match.content);
  }

  private setLink(rel: string, href: string, hreflang?: string): void {
    const selector = `link[rel="${rel}"]${hreflang ? `[hreflang="${hreflang}"]` : ':not([hreflang])'}`;
    let el = this.doc.head.querySelector<HTMLLinkElement>(selector);
    if (!el) {
      el = this.doc.createElement('link');
      el.rel = rel;
      if (hreflang) el.hreflang = hreflang;
      this.doc.head.appendChild(el);
    }
    el.href = href;
  }

  private apply(): void {
    const override = this.override;
    const data = override ?? this.deepestData();
    const lang = this.languageService.getCurrentLanguage();
    const rawPath = this.router.url.split(/[?#]/)[0];
    const path = ALIASES[rawPath] ?? rawPath;
    const url = SITE + path;

    const routeTitle = override ? String(data['title'] ?? '') : this.text(data['title']);
    const fullTitle = routeTitle
      ? `${routeTitle} — Abderrazzaq El Abdouni`
      : 'Abderrazzaq El Abdouni — Full-Stack Developer';

    const description = this.metaContent(data, 'name', 'description', !!override)
      || this.text('SEO.DEFAULT_DESCRIPTION');
    const ogDescription = this.metaContent(data, 'property', 'og:description', !!override) || description;

    this.title.setTitle(fullTitle);
    this.meta.updateTag({ name: 'description', content: description });
    this.meta.updateTag({ name: 'twitter:title', content: fullTitle });
    this.meta.updateTag({ name: 'twitter:description', content: description });
    this.meta.updateTag({ property: 'og:title', content: fullTitle });
    this.meta.updateTag({ property: 'og:description', content: ogDescription });
    this.meta.updateTag({ property: 'og:type', content: 'website' });
    this.meta.updateTag({ property: 'og:url', content: url });
    this.meta.updateTag({ property: 'og:locale', content: OG_LOCALE[lang] });

    const ogImage = `${SITE}/${ogImageFor(path)}`;
    this.meta.updateTag({ property: 'og:image', content: ogImage });
    this.meta.updateTag({ property: 'og:image:width', content: '1200' });
    this.meta.updateTag({ property: 'og:image:height', content: '630' });
    this.meta.updateTag({ name: 'twitter:image', content: ogImage });
    this.meta.updateTag({ name: 'twitter:card', content: 'summary_large_image' });

    // One URL serves every language, so the canonical is that URL and the only
    // honest hreflang is a self-reference plus x-default. Pointing alternate
    // languages at the same URL would claim distinct documents that don't exist.
    this.setLink('canonical', url);
    this.doc.head.querySelectorAll('link[rel="alternate"]').forEach(l => l.remove());
    this.setLink('alternate', url, lang);
    this.setLink('alternate', url, 'x-default');
  }
}
