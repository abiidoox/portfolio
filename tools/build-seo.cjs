#!/usr/bin/env node
/**
 * Regenerates src/sitemap.xml and src/rss.xml from the data files.
 *
 * One <url> per prerendered route: the static pages, one per project case
 * study, and one per note. The RSS feed carries the notes, newest first.
 * Both files are committed, so CI and deploys only need the files.
 *
 * Run: node tools/build-seo.cjs
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://abderrazzaq-portfolio.netlify.app';
const OUT = path.join(ROOT, 'src', 'sitemap.xml');

const readTs = (...parts) => {
  const file = path.join(ROOT, ...parts);
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
};

const slugify = key => key.toLowerCase().replace(/_/g, '-');

// Projects and notes are plain TS arrays, so a light regex reads their keys
// without a build step (same approach as tools/build-og.cjs). The indentation
// anchor skips prose like "for a project key: 'X' -> 'x'." in comments.
const keysOf = src => {
  const keys = [];
  const re = /^\s+key: '([^']+)'/gm;
  let m;
  while ((m = re.exec(src))) keys.push(m[1]);
  return keys;
};

const projectKeys = keysOf(readTs('src', 'app', 'data', 'projects.data.ts'));

// Notes additionally carry the English title/summary/date the RSS feed needs.
const notes = (() => {
  const src = readTs('src', 'app', 'data', 'notes.data.ts');
  const found = [];
  const re = /key: '([^']+)'[\s\S]*?date: '([^']+)'[\s\S]*?fallbackTitle: '([^']+)'[\s\S]*?fallbackSummary: '([^']+)'/g;
  let m;
  while ((m = re.exec(src))) {
    found.push({ key: m[1], date: m[2], title: m[3], summary: m[4] });
  }
  return found;
})();

const entries = [
  { loc: '/', changefreq: 'monthly', priority: '1.0' },
  { loc: '/projects', changefreq: 'monthly', priority: '0.9' },
  { loc: '/resume', changefreq: 'yearly', priority: '0.8' },
  { loc: '/skills', changefreq: 'yearly', priority: '0.8' },
  { loc: '/contact', changefreq: 'yearly', priority: '0.7' }
];

if (notes.length) {
  entries.push({ loc: '/notes', changefreq: 'monthly', priority: '0.7' });
}

for (const key of projectKeys) {
  entries.push({ loc: `/projects/${slugify(key)}`, changefreq: 'yearly', priority: '0.6' });
}

for (const n of notes) {
  entries.push({ loc: `/notes/${slugify(n.key)}`, changefreq: 'yearly', priority: '0.6' });
}

const urls = entries.map(e => `  <url>
    <loc>${SITE}${e.loc}</loc>
    <changefreq>${e.changefreq}</changefreq>
    <priority>${e.priority}</priority>
  </url>`);

// Keep the note about /about next to the home entry it explains.
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-seo.cjs - run "npm run seo:build" after adding
     projects or notes. Do not hand-edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <!-- /about serves the same page as / and canonicalises to it, so it is
       deliberately absent here: a sitemap must list canonical URLs only. -->
${urls.join('\n')}
</urlset>
`;

fs.writeFileSync(OUT, xml);
console.log(`wrote ${entries.length} URLs to src/sitemap.xml`);

// ---- RSS feed ---------------------------------------------------------
// One feed for the notes, titled in English: the site switches language per
// visitor, but a feed file cannot, and every note page itself is trilingual.
const escapeXml = s => s
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;');

if (notes.length) {
  const items = [...notes]
    .sort((a, b) => b.date.localeCompare(a.date))
    .map(n => {
      const url = `${SITE}/notes/${slugify(n.key)}`;
      const pubDate = new Date(`${n.date}-01T00:00:00Z`).toUTCString();
      return `    <item>
      <title>${escapeXml(n.title)}</title>
      <link>${url}</link>
      <guid isPermaLink="true">${url}</guid>
      <description>${escapeXml(n.summary)}</description>
      <pubDate>${pubDate}</pubDate>
    </item>`;
    })
    .join('\n');

  const rss = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-seo.cjs - run "npm run seo:build" after adding
     or editing notes. Do not hand-edit. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Abderrazzaq El Abdouni \u2014 Notes</title>
    <link>${SITE}/notes</link>
    <description>Short write-ups on how this portfolio is built.</description>
    <language>en</language>
    <atom:link href="${SITE}/rss.xml" rel="self" type="application/rss+xml"/>
${items}
  </channel>
</rss>
`;
  fs.writeFileSync(path.join(ROOT, 'src', 'rss.xml'), rss);
  console.log(`wrote ${notes.length} items to src/rss.xml`);
}
