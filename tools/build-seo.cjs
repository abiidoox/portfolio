#!/usr/bin/env node
/**
 * Regenerates src/sitemap.xml from the data files.
 *
 * One <url> per prerendered route: the static pages plus one per project case
 * study. The file is committed, so CI and deploys only need the file.
 *
 * Run: node tools/build-seo.cjs
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://abderrazzaq-portfolio.netlify.app';
const OUT = path.join(ROOT, 'src', 'sitemap.xml');

const readTs = (...parts) => {
  const file = path.join(ROOT, ...parts);
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
};

const slugify = key => key.toLowerCase().replace(/_/g, '-');

// Projects are a plain TS array, so a light regex reads their keys without a
// build step (same approach as tools/build-og.cjs). The indentation anchor
// skips prose like "for a project key: 'X' -> 'x'." in comments.
const keysOf = src => {
  const keys = [];
  const re = /^\s+key: '([^']+)'/gm;
  let m;
  while ((m = re.exec(src))) keys.push(m[1]);
  return keys;
};

const projectKeys = keysOf(readTs('src', 'app', 'data', 'projects.data.ts'));

const entries = [
  { loc: '/', changefreq: 'monthly', priority: '1.0' },
  { loc: '/projects', changefreq: 'monthly', priority: '0.9' },
  { loc: '/resume', changefreq: 'yearly', priority: '0.8' },
  { loc: '/skills', changefreq: 'yearly', priority: '0.8' },
  { loc: '/contact', changefreq: 'yearly', priority: '0.7' }
];

for (const key of projectKeys) {
  entries.push({ loc: `/projects/${slugify(key)}`, changefreq: 'yearly', priority: '0.6' });
}

const urls = entries.map(e => `  <url>
    <loc>${SITE}${e.loc}</loc>
    <changefreq>${e.changefreq}</changefreq>
    <priority>${e.priority}</priority>
  </url>`);

// Keep the note about /about next to the home entry it explains.
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-seo.cjs - run "npm run seo:build" after adding
     projects. Do not hand-edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <!-- /about serves the same page as / and canonicalises to it, so it is
       deliberately absent here: a sitemap must list canonical URLs only. -->
${urls.join('\n')}
</urlset>
`;

fs.writeFileSync(OUT, xml);
console.log(`wrote ${entries.length} URLs to src/sitemap.xml`);
