#!/usr/bin/env node
/**
 * Refreshes the live GitHub numbers shown on the About page.
 *
 * The portfolio should not lie, and it should not hit the GitHub API from the
 * browser either (rate limits, privacy, and a spinner on every visit). This
 * script runs at build time, snapshots a few honest numbers, and writes them
 * to a TypeScript file the app imports directly.
 *
 * Run: node tools/fetch-github.cjs   (npm run data:github)
 */
const https = require('https');
const fs = require('fs');
const path = require('path');

const USER = 'abiidoox';
const OUT = path.resolve(__dirname, '..', 'src', 'app', 'data', 'github-stats.ts');

function getJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, {
      headers: {
        'User-Agent': 'portfolio-build-script',
        'Accept': 'application/vnd.github+json'
      }
    }, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try { resolve(JSON.parse(data)); } catch (error) { reject(error); }
      });
    }).on('error', reject);
  });
}

(async () => {
  const user = await getJson(`https://api.github.com/users/${USER}`);
  if (!user || !user.login) throw new Error(`unexpected user payload: ${JSON.stringify(user).slice(0, 200)}`);

  const repos = await getJson(`https://api.github.com/users/${USER}/repos?per_page=100&sort=pushed`);
  if (!Array.isArray(repos)) throw new Error(`unexpected repos payload: ${JSON.stringify(repos).slice(0, 200)}`);

  const languageCounts = {};
  let latestPush = null;
  for (const repo of repos) {
    if (repo.language) languageCounts[repo.language] = (languageCounts[repo.language] || 0) + 1;
    // Forks are other people's work; the last real push should be ours.
    if (!repo.fork && repo.pushed_at && (!latestPush || repo.pushed_at > latestPush.at)) {
      latestPush = { repo: repo.name, at: repo.pushed_at };
    }
  }

  const languages = Object.entries(languageCounts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5)
    .map(([name, count]) => ({ name, count }));

  const stats = {
    login: user.login,
    name: user.name || user.login,
    publicRepos: user.public_repos,
    followers: user.followers,
    fetchedAt: new Date().toISOString(),
    latestPush,
    languages
  };

  const content = `/**\n * Live GitHub numbers, generated by tools/fetch-github.cjs.\n * Do not edit by hand: run \`npm run data:github\` instead.\n */\nexport interface GithubStats {\n  login: string;\n  name: string;\n  publicRepos: number;\n  followers: number;\n  /** ISO timestamp of the script run. */\n  fetchedAt: string;\n  latestPush: { repo: string; at: string } | null;\n  languages: { name: string; count: number }[];\n}\n\nexport const GITHUB_STATS: GithubStats = ${JSON.stringify(stats, null, 2)};\n`;

  fs.writeFileSync(OUT, content);
  console.log(`wrote ${OUT} (${stats.publicRepos} repos, latest push ${latestPush ? latestPush.repo : 'n/a'})`);
})().catch(error => {
  console.error('fetch-github failed:', error.message);
  process.exit(1);
});
